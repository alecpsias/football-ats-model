"""Fail-closed 5,000-run receipts for actual NFL and CFB pregame model outputs.

A receipt certifies the saved model result and source/version metadata. It does
NOT certify predictive calibration, correct market odds, or confirmed injuries.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import math
from datetime import datetime, timezone
from pathlib import Path
from nfl_challenger_policy import ACTIVE_CHALLENGER_VERSION

RUNS = 5000


def require(value, message):
    if not value:
        raise ValueError(message)


def number(value, name):
    require(type(value) in (int, float) and math.isfinite(value),
            f"Missing or invalid {name}")
    return value


def stamp(value):
    require(isinstance(value, str) and value, "Missing UTC timestamp")
    d = datetime.fromisoformat(value.replace("Z", "+00:00"))
    require(d.tzinfo is not None, "Timestamp must be timezone-aware")
    return d.astimezone(timezone.utc)


def verify(data, league, run_id, git_sha, raw_sha256):
    """Reject mismatched run IDs, unrun simulations, old/late forecasts."""
    require(league in ("NFL", "CFB"), "Unsupported league")
    require(isinstance(run_id, str) and run_id.isdigit(), "Missing GitHub run ID")
    require(isinstance(git_sha, str) and len(git_sha) == 40 and
            all(c in "0123456789abcdef" for c in git_sha.lower()),
            "Missing commit SHA")
    require(isinstance(data, dict), "Invalid result JSON")
    require(isinstance(data.get("game_id"), str) and data["game_id"],
            "Missing game ID")
    home, away = data.get("home"), data.get("away")
    require(isinstance(home, str) and isinstance(away, str) and
            home and away and home != away, "Invalid matchup")
    require(isinstance(raw_sha256, str) and len(raw_sha256) == 64,
            "Missing output digest")
    if league == "CFB":
        require(data.get("mode") == "pregame" and
                data.get("status") == "FRESH_PREGAME_PROJECTION_LOCKED",
                "CFB requested game was not projected pregame")
        require(str(data.get("github_run_id")) == run_id,
                "CFB forecast not generated by this run")
        require(data.get("git_commit_sha") == git_sha,
                "CFB forecast commit does not match run")
        primary = data.get("simulation") or {}
        challenge = (data.get("build16_challenger") or {}).get("simulation") or {}
        require(primary.get("simulations") == RUNS, "CFB baseline not 5000")
        require(challenge.get("simulations") == RUNS, "CFB Build16 not 5000")
        require(data.get("build16_not_primary") is True,
                "CFB challenger not isolated")
        require(isinstance(data.get("source_manifest_sha256"), str) and
                len(data["source_manifest_sha256"]) == 64,
                "CFB input snapshot digest missing")
        forecast_time = stamp(data.get("prediction_generated_at_utc"))
        source_time = stamp(data.get("source_snapshot_at_utc"))
        kickoff = stamp(data.get("kickoff_utc"))
        require(source_time <= forecast_time < kickoff,
                "CFB source/forecast is after kickoff")
        model_version = data.get("model_variant")
        challenger_version = (data.get("build16_challenger") or {}).get("version")
        source_fingerprint = data["source_manifest_sha256"]
        scores = (data.get("simulated_score_home"), data.get("simulated_score_away"),
                  data.get("simulated_margin_home"))
        require(all(number(v, "CFB projected score/margin") is not None for v in scores),
                "CFB projection incomplete")
        require(number((data.get("build16_challenger") or {}).get("mean_margin_home"), "CFB challenger margin") is not None,
                "CFB challenger projection incomplete")
        challenger_runs = challenge["simulations"]
    else:
        require(data.get("status") == "EXPLORATORY_CORE_PROJECTION_UNCALIBRATED",
                "NFL game was not projected")
        primary = data.get("baseline_simulation") or {}
        challenge = (data.get("challenger") or {}).get("candidate") or {}
        require(primary.get("simulations") == RUNS, "NFL baseline not 5000")
        require((data.get("audit") or {}).get("simulation_runs") == RUNS,
                "NFL audit does not match baseline")
        require(challenge.get("n") == RUNS and
                challenge.get("promoted_to_primary") is False,
                "NFL sole challenger not executed for 5000 runs")
        require(data.get("challenger", {}).get("version") == ACTIVE_CHALLENGER_VERSION,
                "NFL active challenger version unexpected")
        require(str(data.get("execution", {}).get("github_run_id")) == run_id,
                "NFL forecast was not generated by this GitHub run")
        require(data.get("execution", {}).get("git_commit_sha") == git_sha,
                "NFL forecast commit does not match runner")
        source_time = stamp(data.get("data_as_of_utc"))
        forecast_time = stamp(data.get("generated_at_utc"))
        kickoff = stamp(data.get("kickoff_utc"))
        require(source_time <= forecast_time < kickoff,
                "NFL source or forecast timestamp is after kickoff")
        require(isinstance(data.get("audit", {}).get("source_sha256"), dict) and
                data["audit"]["source_sha256"], "NFL input digests missing")
        model_version = data["audit"].get("model_version")
        challenger_version = data["challenger"]["version"]
        source_fingerprint = data["audit"]["source_sha256"]
        number(data.get("projected_home_margin"), "NFL baseline margin")
        number(challenge.get("mean_margin_home"), "NFL challenger margin")
        challenger_runs = challenge["n"]
    require(isinstance(model_version, str) and model_version,
            "Model version missing")
    require(isinstance(challenger_version, str) and challenger_version,
            "Challenger version missing")
    return {
        "schema": "simulation_execution_receipt_v1",
        "status": "VERIFIED_5000_SIMULATIONS_RESEARCH_ONLY",
        "league": league, "game_id": data["game_id"],
        "home": home, "away": away,
        "github_run_id": run_id, "git_commit_sha": git_sha,
        "github_actions_url": "https://github.com/alecpsias/football-ats-model/actions/runs/" + run_id,
        "source_as_of_utc": source_time.isoformat(),
        "forecast_at_or_after_source_utc": forecast_time.isoformat(),
        "kickoff_utc": kickoff.isoformat(),
        "source_fingerprint": source_fingerprint,
        "result_sha256": raw_sha256,
        "primary_model_version": model_version,
        "challenger_model_version": challenger_version,
        "primary_runs": RUNS, "challenger_runs": challenger_runs,
        "primary_home_margin": (data["simulated_margin_home"] if league == "CFB"
                                else data["projected_home_margin"]),
        "challenger_home_margin": (data["build16_challenger"]["mean_margin_home"]
                                   if league == "CFB"
                                   else data["challenger"]["candidate"]["mean_margin_home"]),
        "ats_calibrated": False, "market_quote_verified": False,
        "warning": "This verifies execution, not an empirically validated ATS edge."
    }


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--league", choices=("NFL", "CFB"), required=True)
    p.add_argument("--input", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--run-id", required=True)
    p.add_argument("--git-sha", required=True)
    args = p.parse_args()
    source = Path(args.input)
    raw = source.read_bytes()
    receipt = verify(json.loads(raw), args.league, args.run_id,
                     args.git_sha, hashlib.sha256(raw).hexdigest())
    target = Path(args.out)
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.exists():
        raise FileExistsError("Receipt already exists; refusing overwrite")
    target.write_text(json.dumps(receipt, indent=2, sort_keys=True) + "\n")
    print(json.dumps(receipt, indent=2))


if __name__ == "__main__":
    main()
